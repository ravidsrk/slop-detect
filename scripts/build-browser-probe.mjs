#!/usr/bin/env node
// Generates standalone browser-bundle/*.js probes from @slop-detect/core so the
// Rust raw-CDP runner (`crates/slop-browser`) embeds zero-Node, zero-Playwright
// DOM collection scripts directly via `include_str!`.
//
// Usage:
//   bun run --filter @slop-detect/core build && node scripts/build-browser-probe.mjs

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '..');

const core = await import('../packages/core/dist/index.js');

const outDir = path.join(ROOT, 'browser-bundle');
fs.mkdirSync(outDir, { recursive: true });

const probeSource = `// GENERATED BY scripts/build-browser-probe.mjs — DO NOT EDIT BY HAND.
// Definitions version: ${core.DEFINITIONS_VERSION}
${core.buildPageScript({ includeSystem: true, includeExperimental: false })}
`;

const mobileReflowSource = `// GENERATED BY scripts/build-browser-probe.mjs — DO NOT EDIT BY HAND.
// Definitions version: ${core.DEFINITIONS_VERSION}
${core.buildMobileReflowScript()}
`;

fs.writeFileSync(path.join(outDir, 'probe.js'), probeSource);
fs.writeFileSync(path.join(outDir, 'mobile-reflow.js'), mobileReflowSource);

console.log(
  `wrote browser-bundle/probe.js (${probeSource.length} B) and browser-bundle/mobile-reflow.js (${mobileReflowSource.length} B)`
);
