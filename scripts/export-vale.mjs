#!/usr/bin/env node
// W-05 (#311): Deterministic Vale style exporter for Slop Detector copy rules.
//
// Reads the canonical copy rule definitions from @slop-detect/core and generates
// Vale rule files under `styles/SlopDetect/*.yml` plus `styles/SlopDetect/meta.json`.
//
// Policy guarantees:
//   1. Error/Warning artifact rules (C-02, C-03, C-05, C-06) export as `level: error`
//      or `level: warning`.
//   2. Phrase/vocabulary rules export as `level: suggestion`.
//   3. Statistical density/dispersion rules that require full-page word-count gates
//      (>= 150 or >= 300 prose words) and DOM-attribute-only rules are explicitly
//      recorded in `excludedRules` in meta.json and never exported as noisy per-line
//      Vale rules.
//   4. C-15 banned signals (formality, contraction rate, readability, sentiment,
//      single-model perplexity) are never exported.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '..');
const OUT_DIR = path.join(ROOT, 'styles', 'SlopDetect');

async function loadCoreCopyDefs() {
  try {
    return await import('../packages/core/dist/index.js');
  } catch {
    const copyMod = await import('../packages/core/src/copyPatterns.ts');
    const defMod = await import('../packages/core/src/definitions.ts');
    return { ...copyMod, ...defMod };
  }
}

const { COPY_PATTERNS, CHATBOT_MARKUP_REGISTRY, BUZZWORDS_BY_ERA, DEFINITIONS_VERSION } =
  await loadCoreCopyDefs();

function yamlQuote(str) {
  return `'${String(str).replace(/'/g, "''")}'`;
}

function normalizeRegexSource(src) {
  return String(src).replace(/\\u([0-9a-fA-F]{4})/g, (_, hex) =>
    String.fromCharCode(parseInt(hex, 16))
  );
}

function buildExistenceRule({
  heading,
  id,
  message,
  level,
  ignorecase = true,
  nonword = false,
  tokens,
}) {
  const lines = [
    `# Generated by scripts/export-vale.mjs from @slop-detect/core (${id}) — DO NOT EDIT MANUALLY`,
    `extends: existence`,
    `message: ${yamlQuote(message)}`,
    `level: ${level}`,
    `ignorecase: ${ignorecase}`,
  ];
  if (nonword) lines.push(`nonword: true`);
  lines.push(`tokens:`);
  for (const t of tokens) {
    lines.push(`  - ${yamlQuote(t)}`);
  }
  return `${heading ? `# ${heading}\n` : ''}${lines.join('\n')}\n`;
}

export function generateValeStyleFiles() {
  const patternMap = new Map(COPY_PATTERNS.map((p) => [p.id, p]));
  const files = new Map();

  // 1. C-02: ChatbotMarkupLeak.yml (level: error)
  const c02 = patternMap.get('chatbot_markup_leak');
  files.set(
    'ChatbotMarkupLeak.yml',
    buildExistenceRule({
      heading: `${c02.id}: ${c02.label}`,
      id: c02.id,
      message: "Leaked chatbot citation or UI markup ('%s'). Remove before publishing.",
      level: 'error',
      ignorecase: true,
      nonword: true,
      tokens: CHATBOT_MARKUP_REGISTRY.map((entry) => normalizeRegexSource(entry.re.source)),
    })
  );

  // 2. C-03: ChatbotReplyResidue.yml (level: error)
  const c03 = patternMap.get('chatbot_reply_residue');
  files.set(
    'ChatbotReplyResidue.yml',
    buildExistenceRule({
      heading: `${c03.id}: ${c03.label}`,
      id: c03.id,
      message: "Chatbot turn framing or refusal residue ('%s') pasted into copy.",
      level: 'error',
      ignorecase: true,
      tokens: [
        '\\bas an ai(?: language model| assistant)?\\b',
        '\\bas a large language model\\b',
        '\\bi cannot fulfill this request\\b',
        '\\bmy knowledge cutoff\\b',
        '\\bi hope this helps!\\s*(?:let me know|feel free)',
        '\\blet me know if you(?:\x27d| would) like me to\\b',
        '\\bregenerate response\\b',
        '\\bcontinue generating\\b',
      ],
    })
  );

  // 3. C-05: UnfilledPlaceholders.yml (level: error)
  const c05 = patternMap.get('unfilled_placeholders');
  files.set(
    'UnfilledPlaceholders.yml',
    buildExistenceRule({
      heading: `${c05.id}: ${c05.label}`,
      id: c05.id,
      message: "Unfilled template placeholder ('%s'). Replace with concrete copy.",
      level: 'error',
      ignorecase: true,
      nonword: true,
      tokens: [
        '\\[(?:Your|Insert|Add|Enter)\\s[^\\]\\n]{1,40}\\]',
        '\\[(?:Company|Product|Brand|Business|Client|Customer|Founder|Startup) Name\\]',
        '\\((?:Add|Insert) [^)]{1,40} here\\)',
        '\\b(?:INSERT|PASTE)_[A-Z0-9_]+\\b',
      ],
    })
  );

  // 4. C-06: LeakedMarkdown.yml (level: error)
  const c06 = patternMap.get('leaked_markdown');
  files.set(
    'LeakedMarkdown.yml',
    buildExistenceRule({
      heading: `${c06.id}: ${c06.label}`,
      id: c06.id,
      message: "Unrendered raw Markdown syntax ('%s') in visible prose.",
      level: 'error',
      ignorecase: false,
      nonword: true,
      tokens: [
        '(\\*{2}|_{2})(?=\\S)([^\\*\\n]{1,80}?)(?<=\\S)\\1',
        '\\[([^\\]\\n]{1,80})\\]\\((https?:\\/\\/[^\\s)]+)\\)',
      ],
    })
  );

  // 5. C-01 / buzzword_density: Buzzwords.yml (level: suggestion)
  const c01 = patternMap.get('buzzword_density');
  const allBuzzwords = [
    ...BUZZWORDS_BY_ERA.gpt4_2023_2024,
    ...BUZZWORDS_BY_ERA.marketing_2024_2026,
  ];
  files.set(
    'Buzzwords.yml',
    buildExistenceRule({
      heading: `${c01.id}: ${c01.label}`,
      id: c01.id,
      message: "High-frequency default-template buzzword ('%s'). Prefer concrete specifics.",
      level: 'suggestion',
      ignorecase: true,
      tokens: allBuzzwords,
    })
  );

  // 6. antithesis_construction: AntithesisConstruction.yml (level: suggestion)
  const antithesis = patternMap.get('antithesis_construction');
  files.set(
    'AntithesisConstruction.yml',
    buildExistenceRule({
      heading: `${antithesis.id}: ${antithesis.label}`,
      id: antithesis.id,
      message: "Contrastive antithesis frame ('%s'). State what the product does directly.",
      level: 'suggestion',
      ignorecase: true,
      tokens: [
        "\\bit['’]?s not just\\b",
        '\\bnot just (?:a|an|about)\\b',
        "\\bisn['’]?t just\\b",
        '\\bnot only\\b[^.?!]{1,80}\\bbut also\\b',
        '\\bmore than just\\b',
      ],
    })
  );

  // 7. filler_openers: FillerOpeners.yml (level: suggestion)
  const filler = patternMap.get('filler_openers');
  files.set(
    'FillerOpeners.yml',
    buildExistenceRule({
      heading: `${filler.id}: ${filler.label}`,
      id: filler.id,
      message: "Generic throat-clearing opener ('%s'). Start with the specific problem or claim.",
      level: 'suggestion',
      ignorecase: true,
      tokens: [
        "\\bin today['’]?s (?:fast-paced|ever-evolving|digital|modern|competitive)\\b",
        '\\bin the world of\\b',
        '\\bin an era (?:of|where)\\b',
        '\\bwhen it comes to\\b',
        '\\bat the end of the day\\b',
        '\\bin the realm of\\b',
        '\\bin the ever-(?:evolving|changing|expanding)\\b',
      ],
    })
  );

  // 8. formulaic_closers: FormulaicClosers.yml (level: suggestion)
  const closers = patternMap.get('formulaic_closers');
  files.set(
    'FormulaicClosers.yml',
    buildExistenceRule({
      heading: `${closers.id}: ${closers.label}`,
      id: closers.id,
      message: "Essay-style closer ('%s'). End on a concrete action or fact instead.",
      level: 'suggestion',
      ignorecase: true,
      tokens: [
        '\\b(?:in conclusion|in summary|to sum up|to summarize|all in all|when all is said and done)\\b',
      ],
    })
  );

  // 9. whether_youre: WhetherYoure.yml (level: suggestion)
  const whether = patternMap.get('whether_youre');
  files.set(
    'WhetherYoure.yml',
    buildExistenceRule({
      heading: `${whether.id}: ${whether.label}`,
      id: whether.id,
      message:
        "Audience-spanning 'Whether you're X or Y' construction ('%s'). Name your primary audience.",
      level: 'suggestion',
      ignorecase: true,
      tokens: ["\\bwhether you['’]?re\\b[^.?!]{1,80}\\bor\\b"],
    })
  );

  // 10. bare_antithesis: BareAntithesis.yml (level: suggestion)
  const bareAntithesis = patternMap.get('bare_antithesis');
  files.set(
    'BareAntithesis.yml',
    buildExistenceRule({
      heading: `${bareAntithesis.id}: ${bareAntithesis.label}`,
      id: bareAntithesis.id,
      message: "Bare contrastive frame ('%s').",
      level: 'suggestion',
      ignorecase: true,
      tokens: [
        "\\bit['’]?s not\\s+(?!just\\b)[^,.?!]{2,40},\\s*it['’]?s\\s+",
        '\\bno\\s+[a-z][^,.?!]{1,25},\\s*no\\s+[a-z][^,.?!]{1,25},\\s*just\\s+',
      ],
    })
  );

  // 11. announced_structure: AnnouncedStructure.yml (level: suggestion)
  const announced = patternMap.get('announced_structure');
  files.set(
    'AnnouncedStructure.yml',
    buildExistenceRule({
      heading: `${announced.id}: ${announced.label}`,
      id: announced.id,
      message: "Announced essay structure ('%s'). Deliver the substance without meta-narration.",
      level: 'suggestion',
      ignorecase: true,
      tokens: [
        "\\bin this (?:post|article|guide|page|piece|section)\\b[^.?!]{0,60}\\b(?:we(?:'ll| will)|you(?:'ll| will)|let['’]?s) (?:cover|explore|examine|walk through|break down|look at)\\b",
        '\\bby the end of this (?:post|article|guide|page)\\b',
      ],
    })
  );

  // 12. context_leak_copy: ContextLeakCopy.yml (level: suggestion)
  const contextLeak = patternMap.get('context_leak_copy');
  files.set(
    'ContextLeakCopy.yml',
    buildExistenceRule({
      heading: `${contextLeak.id}: ${contextLeak.label}`,
      id: contextLeak.id,
      message: "Template boilerplate phrase ('%s') — verify it accurately describes this product.",
      level: 'suggestion',
      ignorecase: true,
      tokens: [
        '\\bnever leave(?:s)? your (?:browser|device|machine)\\b',
        '\\bbuilt with [a-z0-9.+-]+[^.?!\\n]{0,40}\\bwritten (?:in|from) [a-z0-9.+-]+',
      ],
    })
  );

  const exportedPatternIds = [
    'chatbot_markup_leak',
    'chatbot_reply_residue',
    'unfilled_placeholders',
    'leaked_markdown',
    'buzzword_density',
    'antithesis_construction',
    'filler_openers',
    'formulaic_closers',
    'whether_youre',
    'bare_antithesis',
    'announced_structure',
    'context_leak_copy',
  ];

  const excludedRules = COPY_PATTERNS.filter((p) => !exportedPatternIds.includes(p.id)).map(
    (p) => ({
      id: p.id,
      reason:
        p.status === 'retired'
          ? 'retired-rule'
          : p.statistical
            ? 'requires-document-level-density-or-150-word-prose-gate'
            : 'requires-dom-or-unicode-codepoint-inspection',
    })
  );

  const meta = {
    style: 'SlopDetect',
    definitionsVersion: DEFINITIONS_VERSION,
    exportedRules: Array.from(files.keys()).map((file) => ({
      file,
      level: file.match(/Chatbot|Placeholder|LeakedMarkdown/) ? 'error' : 'suggestion',
    })),
    exportedPatternIds,
    excludedRules,
    bannedSignalsPolicy:
      'C-15: Formality/contraction rate, lexical diversity/readability, positive sentiment, and single-model perplexity are never scored or exported.',
  };

  files.set('meta.json', `${JSON.stringify(meta, null, 2)}\n`);
  return files;
}

export function writeValeStyleFiles(outDir = OUT_DIR) {
  fs.mkdirSync(outDir, { recursive: true });
  const files = generateValeStyleFiles();
  for (const [name, content] of files.entries()) {
    fs.writeFileSync(path.join(outDir, name), content, 'utf8');
  }
  return files;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const checkOnly = process.argv.includes('--check');
  const expected = generateValeStyleFiles();
  if (checkOnly) {
    for (const [name, content] of expected.entries()) {
      const target = path.join(OUT_DIR, name);
      if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== content) {
        process.stderr.write(`Vale style drift detected in styles/SlopDetect/${name}\n`);
        process.exit(1);
      }
    }
    process.stdout.write(`Vale style files (${expected.size}) are up to date.\n`);
  } else {
    writeValeStyleFiles(OUT_DIR);
    process.stdout.write(`Exported ${expected.size} files to styles/SlopDetect/\n`);
  }
}
